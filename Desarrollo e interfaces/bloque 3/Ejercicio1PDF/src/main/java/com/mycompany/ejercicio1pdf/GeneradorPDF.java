    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
          String nombre = jTextField_Nombre.getText();
        String direccion = jTextField_Direccion.getText();
        String telefono = jTextField_Telefono.getText();

    try {
        JasperReport jasperReport = JasperCompileManager.compileReport(crearDiseno());

        Map<String, Object> parameters = new HashMap<>();
        parameters.put("NombreUsuario", nombre);
        parameters.put("DireccionUsuario", direccion);
        parameters.put("TelefonoUsuario", telefono);

        JREmptyDataSource dataSource = new JREmptyDataSource();

        JasperPrint jasperPrint = JasperFillManager.fillReport(jasperReport, parameters, dataSource);

        String outputPdfPath = "reporte.pdf";
        JasperExportManager.exportReportToPdfFile(jasperPrint, outputPdfPath);

        JasperViewer.viewReport(jasperPrint, false);

        JOptionPane.showMessageDialog(this, "El reporte ha sido generado correctamente como pdf",
                "Éxito", JOptionPane.INFORMATION_MESSAGE);
    } catch (Exception e) {
    e.printStackTrace();
    Throwable causa = e;
    while (causa.getCause() != null) {
        causa = causa.getCause();
    }
    JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage() + "\n\nCausa real: " + causa,
            "Error", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_jButton1ActionPerformed


    /** Construye el informe por código (equivale a Ejercicio1.jrxml, sin depender del parseo XML). */
    private JasperDesign crearDiseno() throws Exception {
        JasperDesign design = new JasperDesign();
        design.setName("Ejercicio1");
        design.setPageWidth(595);
        design.setPageHeight(842);
        design.setColumnWidth(515);
        design.setLeftMargin(40);
        design.setRightMargin(40);
        design.setTopMargin(40);
        design.setBottomMargin(40);

        for (String nombre : new String[]{"NombreUsuario", "DireccionUsuario", "TelefonoUsuario"}) {
            JRDesignParameter p = new JRDesignParameter();
            p.setName(nombre);
            p.setValueClass(String.class);
            design.addParameter(p);
        }

        JRDesignBand title = new JRDesignBand();
        title.setHeight(50);
        JRDesignStaticText titulo = new JRDesignStaticText();
        titulo.setX(0);
        titulo.setY(0);
        titulo.setWidth(515);
        titulo.setHeight(40);
        titulo.setText("Datos del usuario");
        title.addElement(titulo);
        design.setTitle(title);

        JRDesignBand detail = new JRDesignBand();
        detail.setHeight(80);
        String[] params = {"NombreUsuario", "DireccionUsuario", "TelefonoUsuario"};
        for (int i = 0; i < params.length; i++) {
            JRDesignTextField tf = new JRDesignTextField();
            tf.setX(0);
            tf.setY(i * 25);
            tf.setWidth(515);
            tf.setHeight(20);
            tf.setExpression(new JRDesignExpression("$P{" + params[i] + "}"));
            detail.addElement(tf);
        }
        ((JRDesignSection) design.getDetailSection()).addBand(detail);
        return design;
    }

